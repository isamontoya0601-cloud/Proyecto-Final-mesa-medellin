-- Tablas --

-- Tabla Usuario -- 

CREATE TABLE usuario(
        
        u_id_usuario            NUMBER GENERATED BY DEFAULT AS IDENTITY,
        u_nombre_completo       VARCHAR2(50) NOT NULL,
        u_telefono              NUMBER NOT NULL,
        u_correo                VARCHAR2(150) NOT NULL,
        u_ciudad_origen         VARCHAR2(50),
        u_tipo_cliente          VARCHAR2(20) NOT NULL,
        u_estado                VARCHAR2(20) NOT NULL,
        
        CONSTRAINT pk_id_usuario PRIMARY KEY(u_id_usuario),
        CONSTRAINT uk_correo_usuario UNIQUE(u_correo),
        CONSTRAINT ck_tipo_cliente_usuario CHECK (u_tipo_cliente IN ('FRECUENTE', 'OCASIONAL', 'VIP')),
        CONSTRAINT ck_estado_usuario CHECK (u_estado IN ('ACTIVO', 'INACTIVO'))
);

-- Tabla Restaurante --

CREATE TABLE restaurante(
        
        r_id_restaurante        NUMBER GENERATED BY DEFAULT AS IDENTITY,
        r_nombre                VARCHAR2(100) NOT NULL,
        r_tipo_cocina           VARCHAR2(50),
        r_direccion             VARCHAR2(150) NOT NULL,
        r_capacidad_maxima      NUMBER NOT NULL,
        r_precio_promedio       NUMBER(10, 2) NOT NULL,
        r_estado                VARCHAR2(20) NOT NULL,
        
        CONSTRAINT pk_id_restaurante PRIMARY KEY(r_id_restaurante),
        CONSTRAINT ck_capacidad_restaurante CHECK (r_capacidad_maxima > 0),
        CONSTRAINT ck_precio_promedio_rest CHECK (r_precio_promedio > 0),
        CONSTRAINT ck_estado_restaurante CHECK (r_estado IN ('ACTIVO', 'EN MANTENIMIENTO', 'INACTIVO'))
);

-- Tabla Zona Medellin -- 

CREATE TABLE zona_medellin(
        
        z_id_zona               NUMBER GENERATED BY DEFAULT AS IDENTITY,
        z_nombre_zona           VARCHAR2(100) NOT NULL,
        z_comuna_barrio         VARCHAR2(100),
        z_sector_turistico      NUMBER(1) NOT NULL, -- Usamos 1 (TRUE) o 0 (FALSE) para el booleano en Oracle
        z_estrato_predominante  NUMBER(1) NOT NULL,
        z_estado                VARCHAR2(20) NOT NULL,
        
        CONSTRAINT pk_id_zona PRIMARY KEY(z_id_zona),
        CONSTRAINT ck_sector_turistico_zona CHECK (z_sector_turistico IN (0, 1)),
        CONSTRAINT ck_estrato_zona CHECK (z_estrato_predominante BETWEEN 1 AND 6),
        CONSTRAINT ck_estado_zona CHECK (z_estado IN ('HABILITADA', 'NO HABILITADA'))
);

-- Tsbla Reserva Restaurantes --

CREATE TABLE reserva_restaurante(
        
        r_id_reserva            NUMBER GENERATED BY DEFAULT AS IDENTITY,
        r_id_usuario            NUMBER NOT NULL,
        r_id_restaurante        NUMBER NOT NULL,
        r_id_zona               NUMBER NOT NULL,
        r_fecha_hora            DATE NOT NULL,
        r_numero_personas       NUMBER DEFAULT 2 NOT NULL,
        r_deposito_reserva      NUMBER(10, 2) NOT NULL,
        r_estado                VARCHAR2(20) NOT NULL,
        
        CONSTRAINT pk_id_reserva PRIMARY KEY(r_id_reserva),
        CONSTRAINT fk_reserva_usuario FOREIGN KEY(r_id_usuario) REFERENCES usuario(u_id_usuario),
        CONSTRAINT fk_reserva_restaurante FOREIGN KEY(r_id_restaurante) REFERENCES restaurante(r_id_restaurante),
        CONSTRAINT fk_reserva_zona FOREIGN KEY(r_id_zona) REFERENCES zona_medellin(z_id_zona),
        CONSTRAINT ck_numero_personas CHECK (r_numero_personas > 0),
        CONSTRAINT ck_deposito_reserva CHECK (r_deposito_reserva >= 0),
        CONSTRAINT ck_estado_reserva CHECK (r_estado IN ('CONFIRMADA', 'COMPLETADA', 'CANCELADA', 'NO ASISTIO'))
);









